    rows = []
    for name, g in [
        *pg.groupby("lang"),
        ("sv excl. bot", pg[(pg.lang == "sv") & ~pg.bot]),
        ("all", pg),
        ("all excl. bot", pg[~pg.bot]),
    ]:
        t = g.dropna(subset=["appeal"])
        rows.append(
            {
                "lang": name,
                "pages": len(g),
                "sitelinks~chars": g.sitelinks.corr(g.char_count, method="spearman"),
                "pages_tagged": len(t),
                "sitelinks~appeal": t.sitelinks.corr(t.appeal, method="spearman"),
                "chars~appeal": t.char_count.corr(t.appeal, method="spearman"),
            }
        )
    s.append(
        "`tourist_appeal` (low/medium/high → 0/1/2) is a `page_tags` field, stored only on rag rows: pages without a rag "
        "row have no tag. It is an LLM classifier's label (Gemma 4 E4B LoRA), not a measured visit signal."
    )
    s.append(table(pd.DataFrame(rows).sort_values("pages", ascending=False)))

    s.append(
        "### 7. Geo questions across borders (dev, ok)\n\nPer anchor country: does the gold set span more than one "
        "country or language (wiki prefix)?"
    )
    s.append(
        table(
            con.sql(f"""with g as (select key, unnest(gold_pages) gid from meta where ok and {DEV} and kind = 'geo'),
        x as (select key, count(distinct p.country) countries, count(distinct split_part(gid, '/', 1)) langs from g join pages p on p.id = g.gid group by 1)
        select a.country anchor_country, count(*) questions, avg((countries > 1)::int) multi_country, avg((langs > 1)::int) multi_language,
               median(m.n_gold) gold_p50
        from meta m join x using (key) join pages a on a.id = m.anchor group by 1 order by 2 desc, 1""").df()
        )
    )
    s.append(
        table(
            con.sql(f"""with g as (select key, unnest(gold_pages) gid from meta where ok and {DEV} and kind = 'geo'),
        x as (select key, count(distinct p.country) countries, count(distinct split_part(gid, '/', 1)) langs from g join pages p on p.id = g.gid group by 1)
        select 'all dev geo' as scope, count(*) questions, avg((countries > 1)::int) multi_country, avg((langs > 1)::int) multi_language from x""").df()
        )
    )
    return s


